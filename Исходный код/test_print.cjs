const assert=require('node:assert/strict'),P=require('./ui/print-tools.js'),data=require('./seed.json');
assert.equal(P.roomNumber('11 (Кабинет начальных классов)'),'11');
assert.equal(P.roomNumber('40 (Кабинет иностранного языка №41)'),'40');
assert.equal(P.roomNumber('Кабинет № 12а'),'12а');
assert.equal(P.roomNumber('№ 5'),'5');
assert.equal(P.roomNumber('13/2 (Кабинет)'),'13/2');
assert.equal(P.roomNumber('Спортивный зал'),'—');
assert.equal(P.roomNumber(null),'—');
assert(data.rooms.every(r=>/^\d/.test(P.roomNumber(r.name))));
assert.equal(P.preferences({font:2,margin:999}).font,9);
assert.equal(P.preferences({font:2,margin:999}).margin,20);
assert.equal(P.preferences({orientation:'bad'}).orientation,'portrait');
assert(P.preferences({subject:false,room:false,teacher:false,group:false}).subject);
assert.equal(P.groupLabel('Физико-математический + Социально-гуманитарный'),'ФМ + СГ');
console.log('Print formatting tests passed: all '+data.rooms.length+' rooms use their leading number.');
assert.equal(P.presets.portrait.orientation,'portrait');
assert.equal(P.presets.portrait.scope,'all');
assert.equal(P.presets.sections.layout,'sections');
assert.equal(P.preferences(P.presets.sections).font,12);
assert.equal(P.presets.landscape.orientation,'landscape');
